const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const assert=require('node:assert/strict'),path=require('node:path')
require('node:fs').mkdirSync(path.resolve(__dirname,'../../.preview-qa'),{recursive:true})
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']})
 try {
  const page=await browser.newPage({viewport:{width:1280,height:720}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)?r.continue():r.fulfill({body:'{}',contentType:'application/json'}))
  await page.goto('http://localhost:4180/')
  const entry=page.getByRole('button',{name:'How does this work?',exact:true})
  await entry.waitFor()
  assert.equal(await entry.evaluate(e=>!!e.closest('#vault-card')),true)
  assert.equal(await entry.evaluate(e=>getComputedStyle(e).borderTopWidth),'0px')
  await entry.scrollIntoViewIfNeeded()
  const sizes=await page.locator('.v5-product-card,#vault-card').evaluateAll(es=>es.map(e=>[e.offsetWidth,e.offsetHeight]))
  const before=await page.evaluate(()=>scrollY)
  await page.screenshot({path:path.resolve('../.preview-qa/revision-entry.png')})
  await entry.click()
  const dialog=page.getByRole('dialog',{name:'How does this work? — demo mode'})
  await dialog.locator('.demo-heading').waitFor()
  await page.waitForTimeout(1000)
  const grid=await page.locator('.main-grid').boundingBox()
  assert.ok(grid.y>=0 && grid.y+grid.height<=720,JSON.stringify(grid))
  assert.deepEqual(await page.locator('.v5-product-card,#vault-card').evaluateAll(es=>es.map(e=>[e.offsetWidth,e.offsetHeight])),sizes)
  const positions=[]
  for(let stage=0;stage<8;stage++) {
   await page.waitForTimeout(600)
   const card=await page.locator('.v5-product-card').evaluate(e=>({visibility:getComputedStyle(e).visibility,opacity:getComputedStyle(e).opacity}))
   assert.deepEqual(card,{visibility:'visible',opacity:'1'})
   const bubble=await dialog.locator('.action-bubble').boundingBox()
   const vault=await dialog.getByTestId('anchored-vault').boundingBox()
   const tickets=await page.locator('.v5-tickets-head').boundingBox()
   assert.ok(bubble.y+bubble.height<tickets.y,'Caption above ticket area at '+stage)
   // The animated token can leave the vault during entry/withdrawal; test its resting ring independently.
   const ring=await dialog.locator('[data-testid="anchored-vault"] > circle').first().boundingBox()
   assert.ok(bubble.x+bubble.width<ring.x,'Caption outside vault action at '+stage)
   positions.push([Math.round(bubble.x),Math.round(bubble.y)])
   if([0,2,4,5,6].includes(stage)) await page.screenshot({path:path.resolve('../.preview-qa/revision-stage-'+stage+'.png')})
   await dialog.getByRole('button',{name:stage===7?'Done':stage===6?'What if I want to withdraw?':'Next',exact:true}).click()
  }
  assert.ok(new Set(positions.map(p=>p.join(','))).size>=5,'Captions move between actions')
  await dialog.waitFor({state:'detached'});await page.waitForTimeout(900)
  assert.ok(Math.abs(await page.evaluate(()=>scrollY)-before)<2)
  // Capture actual intermediate scroll and opacity values during a second entry.
  await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(200)
  await entry.evaluate(e=>{
   window.transitionSamples=[];const start=performance.now()
   function record(){const d=document.querySelector('[role=dialog]');if(d) window.transitionSamples.push({y:scrollY,opacity:Number(getComputedStyle(d).opacity),realOpacity:Number(getComputedStyle(document.querySelector('.countdown-center')).opacity)});if(performance.now()-start<900)requestAnimationFrame(record)}
   requestAnimationFrame(record);e.click()
  })
  await page.waitForTimeout(1000)
  const samples=await page.evaluate(()=>window.transitionSamples)
  assert.ok(samples.some(s=>s.opacity>0 && s.opacity<1),'Demo visibly fades in')
  assert.ok(samples.some(s=>s.realOpacity>0 && s.realOpacity<1),'Real text visibly fades out')
  assert.ok(new Set(samples.map(s=>Math.round(s.y))).size>2,'Scroll passes through intermediate positions')
  await page.waitForTimeout(600)
  await dialog.getByRole('button',{name:'Exit demo',exact:true}).click()
  await page.waitForTimeout(120)
  assert.ok(Number(await dialog.evaluate(e=>getComputedStyle(e).opacity))<1,'Exit fades out')
  await dialog.waitFor({state:'detached'});await page.waitForTimeout(900)
  await page.setViewportSize({width:1440,height:800})
  await entry.click();await dialog.locator('.demo-heading').waitFor();await page.waitForTimeout(1000)
  const other=await page.locator('.main-grid').boundingBox()
  assert.ok(other.y>=0 && other.y+other.height<=800)
  await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'})
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({passed:true,positions,transitionSamples:samples,checks:['entry inside vault, borderless','both cards present throughout','1280x720 and 1440x800 framing','unchanged card sizes','five distinct clear caption anchors','smooth scroll','real-text fade out','demo fade in/out','scroll restored']}))
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
