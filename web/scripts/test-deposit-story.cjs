const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const output = path.resolve(__dirname, '../../.preview-qa')
fs.mkdirSync(output,{recursive:true})
const url = 'http://127.0.0.1:4179/prototypes/deposit-story.html'
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
    const errors = [], network = [], walletCalls = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { const origin = new URL(r.url()).origin; if (!['http://127.0.0.1:4179', 'https://fonts.googleapis.com', 'https://fonts.gstatic.com'].includes(origin)) network.push(r.url()) })
    await page.exposeFunction('recordWalletCall', method => walletCalls.push(method))
    await page.addInitScript(() => { window.ethereum = { request: ({method}) => { window.recordWalletCall(method); throw Error('Demo must not access wallet') } } })
    await page.clock.install({ time: new Date('2026-10-03T00:00:00Z') })
    await page.clock.pauseAt(new Date('2026-10-03T00:00:01Z'))
    await page.goto(url)
    assert.equal(await page.locator('.demo-heading').count(), 0)
    const shot = name => page.screenshot({ path: path.join(output, name + '.png'), fullPage: true })
    const run = ms => page.clock.runFor(ms)
    const next = () => page.getByRole('button', { name: 'Next', exact: true }).click()
    const assertStage = async n => assert.equal(await page.locator('main').getAttribute('data-stage'), String(n))
    await page.getByRole('button', { name: 'See what my deposit does' }).click()
    assert.equal(await page.locator('.demo-heading').textContent(), 'DEMO MODE')
    assert.equal(await page.locator('.wordmark, .preview-tag, .demo-label, .token-select').count(), 0)
    assert.equal(await page.getByText(/DRAW 0[12]|Demo tokens|Interactive demo|No real funds|MOTION STUDY/).count(), 0)
    assert.equal(await page.locator('.story-console, h1, .eyebrow').count(), 0)
    assert.equal(await page.getByTestId('ticket-count').textContent(), '0')
    await shot('v3-ready')
    await next(); await run(4900); await assertStage(1)
    await page.getByRole('button', { name: 'Pause motion' }).click()
    const pausedCount = await page.getByTestId('ticket-count').textContent()
    await run(1500)
    assert.equal(await page.getByTestId('ticket-count').textContent(), pausedCount)
    await page.getByRole('button', { name: 'Resume motion' }).click()
    await next(); await run(2400); await shot('v3-pouring')
    assert.ok(await page.getByTestId('pouring-vessel').count())
    const sizes = await page.locator('[data-ball]').evaluateAll(nodes => [...new Set(nodes.map(n => n.dataset.radius))])
    assert.deepEqual(sizes, ['22'])
    await run(4400); await next(); await assertStage(3)
    await run(1150); await shot('v3-ticket-shine')
    const winnerBubble = await page.locator('.action-bubble').boundingBox()
    const sceneBox = await page.locator('.story-scene').boundingBox()
    assert.ok(winnerBubble.x + winnerBubble.width < sceneBox.x + sceneBox.width * (772/1240), 'Winner bubble must stay left of the entire vault')
    assert.ok(await page.locator('[data-winning-ticket]').count())
    await run(2200); await shot('v3-winner-shine')
    assert.equal(await page.locator('[data-ball="orange"][data-shining]').count(), 1)
    await run(1150); await shot('v3-prize-shine')
    assert.equal(await page.locator('[data-ball^="prize-"][data-shining]').count(), 5)
    await run(2200); await next(); await assertStage(4)
    await run(1650); await shot('v3-hatch-fall')
    await run(5100); await shot('v3-settled')
    await next(); await run(1750)
    assert.equal(await page.getByTestId('ticket-count').textContent(), '0')
    await shot('v3-reset')
    await run(5900); await next(); await assertStage(6)
    await run(1150); await shot('v3-green-ticket')
    await run(5600); await shot('v3-green-winner')
    await run(8000); await shot('v4-green-settled')
    assert.equal(await page.locator('[data-owner="#78efc3"]').count(), 6)
    await page.getByRole('button', { name: 'What if I want to withdraw?', exact: true }).click()
    await assertStage(7)
    await run(2000); await shot('v3-withdrawing')
    await run(3400); await shot('v3-withdrawn')
    assert.equal(await page.getByTestId('ticket-count').textContent(), '0')
    const green = await page.locator('[data-owner="#78efc3"]').evaluateAll(nodes => nodes.map(n => n.getAttribute('transform')))
    assert.equal(green.length, 6)
    green.forEach(s => { const [x, y] = s.match(/[-0-9.]+/g).map(Number); assert.ok(x >= 62 && x <= 322); assert.equal(y, 170) })
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await run(32)
    await assertStage(-1)
    assert.equal(await page.locator('.demo-heading').count(), 0)
    assert.equal(await page.locator('.start-button').evaluate(el => el === document.activeElement), true)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 })
      await page.getByRole('button', { name: 'See what my deposit does' }).click()
      for (let step = 0; step < 8; step++) {
        await assertStage(step)
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
        const box = await page.locator('.action-bubble').boundingBox()
        assert.ok(box.x >= 0 && box.x + box.width <= width)
        if (step === 3) {
          const svg = await page.locator('.story-scene').boundingBox()
          assert.ok(box.y + box.height < svg.y + svg.height * (700/1175), 'Mobile winner bubble must stay above reveal area')
          await shot('v5-mobile-' + width + '-winner')
        }
        if ([2,4,6,7].includes(step)) await shot('v3-mobile-' + width + '-stage-' + step)
        const name = step === 7 ? 'Done' : step === 6 ? 'What if I want to withdraw?' : 'Next'
        await page.getByRole('button', { name, exact: true }).click()
      }
    }
    assert.deepEqual(errors, []); assert.deepEqual(network, []); assert.deepEqual(walletCalls, [])
    const result = { status: 'passed', browserErrors: errors, unexpectedRequests: network, walletCalls, checks: ['all eight stages', 'pause freezes', 'equal 22px ball radii', 'ticket shines before travel', 'winner reaction precedes all prizes', 'six green tokens after win', 'all six green tokens withdraw', 'entries reset', 'Done restores normal preview', 'reduced motion all stages', '390px and 320px bubbles fit'], visualApproval: 'PENDING USER REVIEW' }
    fs.writeFileSync(path.join(output, 'results-v3.json'), JSON.stringify(result, null, 2))
    console.log(JSON.stringify(result, null, 2))
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
